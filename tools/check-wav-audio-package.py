#!/usr/bin/env python3
"""Real offline WAV-to-package CLI acceptance; no runtime capability claims."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def snapshot(root):
    return {p.relative_to(root).as_posix(): p.read_bytes()
            for p in sorted(root.rglob('*')) if p.is_file()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--evidence', type=Path, required=True)
    parser.add_argument('--importer', type=Path, required=True)
    parser.add_argument('--package-cli', type=Path, required=True)
    args = parser.parse_args()
    evidence = args.evidence.resolve()
    evidence.mkdir(parents=True, exist_ok=False)
    importer, package_cli = str(args.importer.resolve()), str(args.package_cli.resolve())
    sequence = 0

    def run(label, command, success=True):
        nonlocal sequence
        sequence += 1
        log_path = evidence / f'{sequence:02}-{label}.log'
        log_path.write_text('+ ' + ' '.join(command) + '\n', encoding='utf-8')
        try:
            result = subprocess.run(command, capture_output=True, text=True, timeout=120)
        except (OSError, subprocess.TimeoutExpired) as error:
            with log_path.open('a', encoding='utf-8') as log:
                log.write(f'Execution failed: {error}\n')
            raise
        log_path.write_text(
            '+ ' + ' '.join(command) + '\n' + result.stdout + '\nSTDERR:\n'
            + result.stderr + f'\nexit={result.returncode}\n', encoding='utf-8')
        require((result.returncode == 0) == success,
                f'{label}: unexpected exit {result.returncode}; see retained log')
        return result

    source = evidence / 'source'
    source.mkdir()
    samples = (0, 1024, 4096, 8192, 4096, 0, -4096, -8192) * 60
    pcm = struct.pack('<' + 'h' * len(samples), *samples)
    fmt = struct.pack('<HHIIHH', 1, 1, 48000, 96000, 2, 16)
    body = b'WAVEfmt ' + struct.pack('<I', len(fmt)) + fmt + b'data' + struct.pack('<I', len(pcm)) + pcm
    wav = b'RIFF' + struct.pack('<I', len(body)) + body
    (source / 'original.wav').write_bytes(wav)
    # Original generated sample sequence, deliberately not downloaded third-party audio.
    license_bytes = b'Original synthetic fixture generated by check-wav-audio-package.py.\nPermission is granted to use, copy, modify and distribute this fixture for any purpose.\n'
    (source / 'LICENSE.txt').write_bytes(license_bytes)
    before = snapshot(source)

    def command(output, wav_path=None, source_dir=source):
        return [importer, '--wav', str(wav_path or source_dir / 'original.wav'),
                '--asset-id', 'a_0000000000000001', '--name', 'collect-sfx',
                '--version', '1.0.0', '--license', str(source_dir / 'LICENSE.txt'),
                '--out', str(output)]

    package = evidence / 'package'
    run('import', command(package))
    first = snapshot(package)
    require(snapshot(source) == before, 'source changed after successful import')
    relocated = evidence / 'relocated-source'
    shutil.copytree(source, relocated)
    repeat = evidence / 'relocated-package'
    run('relocated-import', command(repeat, source_dir=relocated))
    require(snapshot(repeat) == first, 'relocation changed package bytes')
    manifest = json.loads(first['orr.package.json'])
    expected_payload = struct.pack('<II', 48000, len(samples)) + pcm
    digest = hashlib.sha256(expected_payload).digest()
    payload_path = 'cooked/objects/' + digest.hex() + '.bin'
    expected_files = {'LICENSE.txt', 'cooked/view.manifest.bin', payload_path}
    require(set(first) == expected_files | {'orr.package.json'}, 'unexpected output file set')
    require(manifest == {'schema': 1, 'name': 'collect-sfx', 'version': '1.0.0',
                         'engine': '^0.0.1', 'capabilities': ['collect-audio'],
                         'dependencies': {}, 'files': sorted(expected_files)}, 'package metadata mismatch')
    expected_oram = (b'ORAM' + struct.pack('<III', 1, 2, 1)
                     + struct.pack('<QIIQ', 1, 2, 1, len(expected_payload)) + digest)
    require(first['cooked/view.manifest.bin'] == expected_oram, 'ORAM metadata/digest mismatch')
    require(first[payload_path] == expected_payload, 'canonical PCM payload mismatch')
    require(first['LICENSE.txt'] == license_bytes, 'license bytes changed')
    run('existing-output-refused', command(package), success=False)
    require(snapshot(package) == first and snapshot(source) == before, 'collision changed bytes')
    run('source-directory-output-refused', command(source), success=False)
    require(snapshot(source) == before, 'source collision changed bytes')
    run('source-file-output-refused', command(source / 'original.wav'), success=False)
    require(snapshot(source) == before, 'file collision changed source')
    malformed = evidence / 'malformed.wav'
    malformed.write_bytes(wav[:-1])
    invalid_output = evidence / 'invalid-package'
    run('malformed-refused', command(invalid_output, wav_path=malformed), success=False)
    require(not invalid_output.exists() and malformed.read_bytes() == wav[:-1], 'malformed input published output or changed input')
    for label, extra in [('missing-flag', []), ('unknown-flag', ['--unknown']),
                         ('duplicate-flag', ['--name', 'collect-sfx'])]:
        cmd = [importer] if label == 'missing-flag' else command(evidence / label) + extra
        run(label, cmd, success=False)
        require(not (evidence / label).exists(), 'invalid arguments published output')
    fifo_status = 'not applicable: Windows has no os.mkfifo'
    if os.name != 'nt':
        fifo = evidence / 'special.wav'
        os.mkfifo(fifo)
        fifo_output = evidence / 'fifo-package'
        run('fifo-refused', command(fifo_output, wav_path=fifo), success=False)
        require(not fifo_output.exists() and fifo.is_fifo(), 'FIFO refusal changed input or published output')
        fifo_status = 'passed: static FIFO rejected without blocking open'
    run('help', [importer, '--help'])
    project = evidence / 'project'
    project.mkdir()
    project_metadata = b'{"schema":1,"engine":"^0.0.1"}\n'
    (project / 'orr.project.json').write_bytes(project_metadata)
    inspected = json.loads(run('inspect', [package_cli, 'inspect', str(package)]).stdout)
    require(inspected['manifest'] == manifest, 'inspect manifest differs')
    lock = json.loads(run('install', [package_cli, 'install', str(project), '--path', str(package)]).stdout)
    installed = lock['packages']['collect-sfx']
    require(installed == inspected, 'installed package differs from inspection')
    require(installed['files'] == {p: hashlib.sha256(first[p]).hexdigest() for p in expected_files},
            'package lock file hashes mismatch')
    cached = project / '.orr/packages/objects' / installed['digest']
    immutable_before = snapshot(cached)
    require(all(immutable_before[p] == first[p] for p in expected_files), 'snapshot payload differs')
    # Relocate generated inputs away from their original paths, retaining evidence.
    unavailable = evidence / "unavailable-original-inputs"
    unavailable.mkdir()
    for original in (source, relocated, package, repeat):
        original.rename(unavailable / original.name)
        require(not original.exists(), "original source path remains available")
    listed = json.loads(run('list-without-source', [package_cli, 'list', str(project)]).stdout)
    require(listed == lock, 'list changed active lock')
    run('explain-without-source', [package_cli, 'explain', str(project), 'collect-sfx'])
    verified = json.loads(run('verify-without-source', [package_cli, 'verify', str(project)]).stdout)
    require(verified == lock, 'verify changed active lock')
    scoped = json.loads(run('scoped-verify-without-source', [package_cli, 'verify', str(project), '--package', 'collect-sfx']).stdout)
    require(set(scoped['verified_packages']) == {'collect-sfx'} and not scoped['unverified_packages'], 'scoped verification incomplete')
    require(snapshot(cached) == immutable_before, 'read-only verification changed immutable snapshot')
    conflict = evidence / 'conflicting-package'
    shutil.copytree(unavailable / 'package', conflict)
    (conflict / 'LICENSE.txt').write_bytes(license_bytes + b'Changed content, same version.\n')
    project_before_conflict = snapshot(project)
    run('same-version-conflict-refused', [package_cli, 'install', str(project), '--path', str(conflict)], success=False)
    require(snapshot(project) == project_before_conflict, 'version conflict changed project bytes')
    tampered_project = evidence / 'tampered-project'
    shutil.copytree(project, tampered_project)
    tampered_payload = tampered_project / '.orr/packages/objects' / installed['digest'] / payload_path
    tampered_payload.write_bytes(expected_payload[:-1] + bytes([expected_payload[-1] ^ 1]))
    tampered_before = snapshot(tampered_project)
    run('tampered-snapshot-refused', [package_cli, 'verify', str(tampered_project)], success=False)
    require(snapshot(tampered_project) == tampered_before, 'verification repaired or changed corrupted bytes')
    require((project / 'orr.project.json').read_bytes() == project_metadata, 'project metadata changed')
    receipt = {'schema': 1, 'fixture': 'original generated mono PCM16 48000 Hz, 480 frames',
               'license_permission': 'use, copy, modify and distribute for any purpose',
               'payload_sha256': digest.hex(), 'package_digest': installed['digest'],
               'deterministic_relocation': True, 'independent_oram_and_pcm_reconstruction': True,
               'source_preserved_on_success_and_failure': True, 'invalid_input_no_publication': True,
               'installed_verification_without_sources': True, 'immutable_snapshot_unchanged': True,
               'real_package_cli_commands': ['inspect', 'install', 'list', 'explain', 'verify', 'verify --package'],
               'same_version_conflict_preserves_project': True,
               'tampered_snapshot_rejected_without_repair': True,
               'static_fifo_rejection': fifo_status,
               'runtime_audio_preview_play_export_verified': False}
    (evidence / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(receipt, indent=2))


if __name__ == '__main__':
    main()
