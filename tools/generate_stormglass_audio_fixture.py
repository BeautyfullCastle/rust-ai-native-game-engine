#!/usr/bin/env python3
"""Original quiet integer PCM fixture for native Stormglass delivery acceptance.

This generates test data, not a replacement soundbank authoring tool. The real
orr_pkg CLI must publish the bank consumed by the native acceptance producer.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct

CUES = (
    "attack-light", "attack-heavy", "attack-magic", "impact-light", "impact-heavy",
    "summon", "merge", "ui-confirm", "ui-reject", "death",
)
RATE = 48_000
FRAMES = 4_800
LICENSE = """Original synthetic Stormglass audio acceptance fixtures.
These integer triangle-wave samples are generated by
 tools/generate_stormglass_audio_fixture.py in this repository.
They contain no recordings, recovered samples or third-party music.
Licensed under the repository's MIT OR Apache-2.0 terms.
This fixture license does not establish rights to any other audio bank.
"""


def digest(data):
    return hashlib.sha256(data).hexdigest()


def samples(index):
    period = 240 - 12 * index
    result = []
    for frame in range(FRAMES):
        phase = frame % period
        triangle = (4 * phase * 2048 // period - 2048
                    if phase < period // 2
                    else 3 * 2048 - 4 * phase * 2048 // period)
        envelope = min(frame, FRAMES - 1 - frame, 64)
        result.append(triangle * envelope // 64)
    assert len(result) == FRAMES and result[0] == result[-1] == 0
    assert 0 < max(map(abs, result)) <= 2048
    return result


def generate(output):
    output = output.absolute()
    # Refuse existing outputs. Failed generations remain for inspection.
    output.mkdir(mode=0o700)
    inputs = output / "originals"
    inputs.mkdir(mode=0o700)
    license_bytes = LICENSE.encode("utf-8")
    (inputs / "LICENSE.txt").write_bytes(license_bytes)
    records = []
    for index, cue in enumerate(CUES):
        values = samples(index)
        raw = struct.pack("<" + "h" * FRAMES, *values)
        pcm = struct.pack("<II", RATE, FRAMES) + raw
        decoded = b"".join(struct.pack("<ff", value / 32768, value / 32768)
                           for value in values)
        (inputs / (cue + ".pcm")).write_bytes(pcm)
        probes = [[i, values[i]] for i in [0, 1, 64, 120, 1234, 2400, 4798, 4799]]
        records.append({"cue": cue, "frames": FRAMES, "pcm_bytes": len(pcm),
                        "pcm_sha256": digest(pcm), "sample_i16_sha256": digest(raw),
                        "decoded_stereo_f32le_sha256": digest(decoded),
                        "peak_i16": max(map(abs, values)), "sample_probes": probes})
    expected = {"version": 1, "sample_rate": RATE, "frames_per_cue": FRAMES,
                "license_sha256": digest(license_bytes), "cues": records,
                "device_playback_verified": False}
    (output / "expected.json").write_text(json.dumps(expected, indent=2) + "\n")
    return expected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path, help="fresh fixture directory; parent must exist")
    args = parser.parse_args()
    expected = generate(args.output)
    print(json.dumps({"output": str(args.output.absolute()), "cues": len(expected["cues"]),
                      "frames_per_cue": FRAMES, "device_playback_verified": False}))


if __name__ == "__main__":
    main()
